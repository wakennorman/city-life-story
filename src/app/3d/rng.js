/**
 * 可复现随机 —— 3D 世界的**唯一**布局随机源。
 *
 * ── 为什么需要这个文件（2026-09-19） ─────────────────────────────────────
 * 原实现是 world.js / kit.js 各自 `Math.random()`。后果有两层：
 *
 *   ① **验证不可复现**（最要命的一条）。
 *      verify-actors 的"锚点堵死 N 个"在 0~2 之间抖、"车辆全部在行驶"时红时绿。
 *      同一份代码跑三次得到三个结论 —— 那么"绿"到底是修好了，还是这次运气好？
 *      说不清。**说不清的绿 = 假绿**，整个守卫体系的可信度都被它拖垮。
 *
 *   ② **虚构城市不持久**。
 *      同一个地点每次进去，摊位、垃圾桶、电动车的位置都不一样。
 *      今天这条巷子口是水果摊，明天变成大排档 —— 而《城市浮生记》是一个
 *      **有固定地理的城市**，地点该像"记忆里的那条街"，不该每次重掷。
 *
 * ── 用法 ───────────────────────────────────────────────────────────────
 *   world.js::buildLocation 开头 `setRng(locationRng(id))`；
 *   此后 world.js / kit.js 里所有 rnd/pick/chance 都消费这一条流。
 *   同 id → 同种子 → 同布局（可复现）；异 id → 异种子 → 异布局（不雷同）。
 *   要整体换一套城市样貌，只改 CITY_SEED 一个数。
 *
 * ── 纪律（踩过就会再踩） ───────────────────────────────────────────────
 *   ★ **只有"决定布局"的代码可以吃这条流**。
 *     materials.js 的贴图噪点、actors.js 的行为抖动（停顿间隔之类）走各自的
 *     随机源：它们要是也吃这条流，生成顺序一变（贴图是惰性的、角色是异步的）
 *     就会把后面的布局顶歪 —— 布局又变回不可复现，而且**不报错**。
 *
 *   ★ 流是**模块级可变状态**。跨地点时务必重新 `setRng`，否则上一个地点
 *     消费掉的进度会带进下一个地点（第二次进同一地点就和第一次不一样）。
 *
 * ── 与「游戏 RNG 卫生」的关系（别把这两件事混了）──────────────────────
 *   tests/rngHygiene.test.cjs 的立场是：**游戏判定**必须走 `Random.*`（可种子化，
 *   为了 MC 跑分可复现）；而 3D 世界布局属**视觉层**，不参与任何游戏判定，
 *   所以它把 src/js/scene3d.bundle.js 列入了白名单、不要求走 Random。
 *
 *   本文件解决的是**第三件事**，与上面两者都不同：
 *     验证可复现性 —— verify-actors 这类脚本的断言必须"同代码同结果"。
 *   布局若每次重掷，断言就会时红时绿而**无法归因**，那等于断言失效。
 *   所以这里是"给 3D 布局自己一条可播种的流"，
 *   **不**接入游戏的 `Random.*`（那会把视觉层耦合进存档逻辑），
 *   **也**不改动上面的白名单立场。三者各管一段，互不冲突。
 *   续：若哪天真要让 3D 布局参与存档回放，改的是 CITY_SEED 的来源
 *   （例如从存档里读一个 per-save 种子），而不是把它接到 Random 上。
 */

/** 城市种子：改这一个数 = 换一座城。 */
export const CITY_SEED = 20260919;

/** FNV-1a 32 位：把地点 id 之类的字符串折成种子。 */
export function hashSeed(str) {
  let h = 2166136261;
  for (let i = 0; i < str.length; i++) {
    h ^= str.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** mulberry32：小、快、无依赖，分布够用（不是密码学随机，也不需要是）。 */
export function mulberry32(a) {
  return function () {
    a |= 0; a = (a + 0x6D2B79F5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** 按地点派生一条独立流。salt 用于同一地点下再分域（如 'actors'）。 */
export function locationRng(id, salt = 'layout') {
  return mulberry32(hashSeed(`${CITY_SEED}|${salt}|${id}`));
}

/* ── 当前流 ────────────────────────────────────────────────────────────
   默认 Math.random：任何**没被 buildLocation 播种就调用**的路径
   （HUD 图标、单独调某个工厂做测试）仍能跑，不会因为取不到种子就崩。 */
let _fn = Math.random;

export function setRng(fn) {
  _fn = typeof fn === 'function' ? fn : Math.random;
}

/** 取一个 [0,1) 随机数，从当前流。 */
export function rng() {
  return _fn();
}
