/**
 * 根据地点ID和当天天数获取当日环境氛围文字
 * @param {string} locationId 地点ID
 * @param {number} day 当前天数
 * @returns {string|null}
 */
function getLocationFlavor(locationId, day) {
  var flavors = LOCATION_FLAVOR[locationId];
  if (!flavors || flavors.length === 0) return null;
  // 用地点ID长度做二次散列，避免所有地点同一天都显示第一条
  var seed = (locationId.length * 7 + day) % flavors.length;
  return flavors[seed];
}
